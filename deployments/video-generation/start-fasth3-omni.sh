  export FASTVIDEO_H3_ADALN_TABLE="$FASTVIDEO_H3_ADALN_DUMP"
  unset FASTVIDEO_H3_ADALN_DUMP
fi
export FASTVIDEO_H3_VSA_FP4=1
export FASTVIDEO_H3_VSA_FP4_PREFIX=fp8
export FASTVIDEO_H3_VSA_FP4_TWO_LEVEL_P=1
export FASTVIDEO_H3_VSA_FP4_K_SMOOTH=1
