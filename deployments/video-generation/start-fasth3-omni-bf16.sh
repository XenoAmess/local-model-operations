#!/usr/bin/env bash
set -euo pipefail
H3_BF16_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
export CUDA_HOME="$H3_BF16_ROOT/tools/cuda"
export PATH="$CUDA_HOME/bin:$H3_BF16_ROOT/FastVideo/.venv/bin:$PATH"
export LD_LIBRARY_PATH="$CUDA_HOME/lib64${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export CUDA_VISIBLE_DEVICES=0
export FASTVIDEO_SERVE_CONFIG="$H3_BF16_ROOT/fasth3-omni-bf16.yaml"
export FASTVIDEO_H3_ADALN_CACHE=1
# This checkpoint has its own AdaLN projections; never reuse the QAD table.
unset FASTVIDEO_H3_ADALN_TABLE FASTVIDEO_H3_ADALN_DUMP FASTVIDEO_H3_VAE_NVFP4_DECODER
export FASTVIDEO_H3_VSA_FP4=0
export FASTVIDEO_H3_VSA_FINE_ATTENTION=emulator-bf16
export FASTVIDEO_ATTENTION_BACKEND=VIDEO_SPARSE_ATTN_H3
export FASTVIDEO_VSA_TRITON=1 FASTVIDEO_VSA_PTX_BLACKWELL=0 FASTVIDEO_FA4=0
export FASTVIDEO_MINIMAX_H3_FUSIONS=all
export FASTVIDEO_H3_GATE_CHUNK_ROWS=8192 FASTVIDEO_H3_FFN_CHUNK_TOKENS=16384
export FASTVIDEO_STAGE_LOGGING=1
export FASTVIDEO_H3_SP_PROFILE=0
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 PYTHONUNBUFFERED=1 TOKENIZERS_PARALLELISM=false
export MAX_JOBS=2 FLASHINFER_NVCC_THREADS=1 NVCC_THREADS=1 TORCHINDUCTOR_COMPILE_THREADS=1
export CMAKE_BUILD_PARALLEL_LEVEL=2 OMP_NUM_THREADS=8
cd "$H3_BF16_ROOT"
exec "$H3_BF16_ROOT/FastVideo/.venv/bin/python" "$H3_BF16_ROOT/tools/serve_fasth3_omni.py"
